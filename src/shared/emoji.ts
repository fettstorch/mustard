export type EmojiName = keyof typeof EMOJI
export const EMOJI_NAMES = Object.keys(EMOJI) as EmojiName[]

export function emojiMatches(query: string): EmojiName[] {
  const needle = query.toLowerCase().replace(/_/g, '-')
  return needle
    ? EMOJI_NAMES.filter((name) => name.replace(/_/g, '-').includes(needle))
    : EMOJI_NAMES
}
